#include "bsp_rcc.h"

/* 轮询次数上限，不是毫秒值。 */
#define BSP_RCC_READY_TIMEOUT  1000000U

/*******************************************************************************
//  Function   : bsp_rcc_SystemReset
//  Description: 请求 MCU 软件系统复位
//  Param      : None
//  Return     : None
//  Others     : 通过 SYSRESETREQ 复位 MCU，调用后不返回；复位前数据保存由调用方负责
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_rcc_SystemReset(void)
{
    __disable_irq();
    __DSB();
    NVIC_SystemReset();
}
