/*******************************************************************************
//  Function   : bsp_wdg_Init
//  Description: 初始化并启动 IWDG 独立看门狗
//  Param      : None
//  Return     : None
//  Others     : 使用 LSI，默认超时约 250 ms；等待超时调用 APP_ErrorHandler()，
//               成功初始化后需定期喂狗；重复调用仅喂狗，不重新配置
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_wdg_Init(void)
{

    /* SystemInit 已加载 LSI 出厂校准值，此处开启 LSI 并等待就绪。 */
    LL_RCC_LSI_Enable();

    while (LL_RCC_LSI_IsReady() == 0U)
    {
        ;
    }

    /* IWDG 启动后无法通过普通软件接口停止，后续必须持续喂狗。 */
    LL_IWDG_Enable(IWDG);
    LL_IWDG_EnableWriteAccess(IWDG);
    /* T = (Reload + 1) * 32 / 32768，标称超时为 250 ms。 */
    LL_IWDG_SetPrescaler(IWDG, BSP_WDG_PRESCALER);
    LL_IWDG_SetReloadCounter(IWDG, BSP_WDG_RELOAD);

    while (LL_IWDG_IsReady(IWDG) == 0U)
    {
        ;
    }

    /* 首次喂狗加载新重装值，再关闭配置寄存器写访问。 */
    LL_IWDG_ReloadCounter(IWDG);
    LL_IWDG_DisableWriteAccess(IWDG);
}

/*******************************************************************************
//  Function   : bsp_wdg_Refresh
//  Description: 重装 IWDG 计数器，刷新看门狗
//  Param      : None
//  Return     : None
//  Others     : 在系统正常运行路径中调用，间隔应小于实际超时时间并预留裕量
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_wdg_Refresh(void)
{
    LL_IWDG_ReloadCounter(IWDG);
}

