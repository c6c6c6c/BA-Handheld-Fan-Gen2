#ifndef _BSP_WDG_H_
#define _BSP_WDG_H_

#include "main.h"

/* Macro -------------------------------------------------------------------------------------------------------------*/
/* LSI 标称 32768 Hz，实际超时时间受 LSI 频率偏差影响。 */
#define BSP_WDG_PRESCALER                 LL_IWDG_PRESCALER_32
#define BSP_WDG_RELOAD                    255U
/* 等待循环次数上限，不是毫秒值，实际等待时间与 CPU 时钟有关。 */
#define BSP_WDG_READY_TIMEOUT            1000000U

#if BSP_WDG_RELOAD > 0x0FFFU
#error "BSP_WDG_RELOAD exceeds the 12-bit IWDG reload range"
#endif

/* Typedef -----------------------------------------------------------------------------------------------------------*/

/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : bsp_wdg_Init
//  Description: 初始化并启动 IWDG 独立看门狗
//  Param      : None
//  Return     : None
//  Others     : 使用 LSI，默认超时约 250 ms；等待超时调用 APP_ErrorHandler()，
//               成功初始化后需定期喂狗；重复调用仅喂狗，不重新配置
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_wdg_Init(void);

/*******************************************************************************
//  Function   : bsp_wdg_Refresh
//  Description: 重装 IWDG 计数器，刷新看门狗
//  Param      : None
//  Return     : None
//  Others     : 在系统正常运行路径中调用，间隔应小于实际超时时间并预留裕量
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_wdg_Refresh(void);

#endif /* _BSP_WDG_H_ */
