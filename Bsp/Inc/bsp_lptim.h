
/**
 ***********************************************************************************************************************
 * @file    bsp_lptim.h
 * @brief   LPTIM 低功耗定时器配置及接口定义，实现 STOP 模式定时唤醒
 ***********************************************************************************************************************
 * @note
 *          1. 使用 LSI 作为 LPTIM1 时钟源。
 *          2. 通过 32 分频生成低速计数时钟。
 *          3. 使用单次计数模式实现定时唤醒。
 *          4. 通过自动重装载值配置唤醒周期。
 *          5. 重新启动前需要关闭 LPTIM 并执行恢复延时。
 ***********************************************************************************************************************
 */

#ifndef __BSP_LPTIM_H
#define __BSP_LPTIM_H

/* Includes ----------------------------------------------------------------------------------------------------------*/

#include "main.h"


/* Macro -------------------------------------------------------------------------------------------------------------*/

/**
 * @brief LPTIM1 时钟预分频配置
 * @note  使用 LSI 作为 LPTIM1 时钟源；
 *        预分频系数设置为 32；
 *        实际计数频率为 LSI 输入频率除以 32。
 */
#define LPTIM_PRESCALER_VALUE   LL_LPTIM_PRESCALER_DIV32

/**
 * @brief LPTIM1 计数时钟频率
 * @note  单位 Hz。
 *        计算公式：Fcnt = LSI_VALUE / 32。
 *        当 LSI_VALUE 为 32768Hz 时，计数频率为 1024Hz。
 *        实际频率取决于芯片 LSI 振荡器的工作频率。
 */
#define LPTIM_COUNTER_FREQ      (LSI_VALUE / 32U)

/**
 * @brief LPTIM1 单次唤醒周期
 * @note  单位 s。
 *        当前配置为 1s；
 *        可通过修改该宏调整理论唤醒周期。
 */
#define LPTIM_WAKEUP_TIME_S     1U

/**
 * @brief LPTIM1 自动重装载寄存器配置值
 * @note  根据计数频率及唤醒周期计算 ARR。
 *
 *        计算公式：
 *        ARR = LPTIM_COUNTER_FREQ * LPTIM_WAKEUP_TIME_S - 1。
 *
 *        当 LSI = 32768Hz、预分频系数为 32、
 *        唤醒周期为 1s 时：
 *
 *        Fcnt = 32768 / 32 = 1024Hz
 *        ARR  = 1024 * 1 - 1 = 1023。
 *
 *        原 HAL 例程使用的自动重装载值为 1024。
 *        如需与该例程保持相同的 ARR 参数，
 *        可根据实际硬件计数行为调整。
 */
#define LPTIM_AUTORELOAD_VALUE  (LPTIM_COUNTER_FREQ * LPTIM_WAKEUP_TIME_S - 1U)

/**
 * @brief LPTIM1 重新启动前的软件延时计数
 * @note  单位为 NOP 循环次数，不是固定时间单位。
 *
 *        单次计数模式下：
 *        1. 等待本次 ARR 匹配及唤醒完成。
 *        2. 关闭 LPTIM1 外设。
 *        3. 执行指定次数的软件空操作延时。
 *        4. 再次使能 LPTIM1 并启动单次计数。
 *
 *        当前配置为 900 次循环，
 *        参考 HAL 例程 APP_DelayNops(900)。
 *
 *        实际延时时间与 MCU 主频、编译器优化
 *        及循环指令开销有关，需要通过实测确认。
 */
#define LPTIM_RESTART_DELAY_NOP 900U


/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : bsp_lptim_Init
//  Description: 初始化 LPTIM1 低功耗定时器及中断唤醒配置
//  Param      : None
//  Return     : None
//  Others     : 使能 LSI 并配置 LPTIM1 时钟源；
//               设置 LPTIM1 预分频及寄存器更新方式；
//               配置 EXTI 及 NVIC 中断唤醒通路；
//               使能 ARR 匹配中断；
//               为 STOP 模式定时唤醒提供硬件基础
*******************************************************************************/
void bsp_lptim_Init(void);


/*******************************************************************************
//  Function   : lptim_start
//  Description: 启动 LPTIM1 单次计数
//  Param      : None
//  Return     : None
//  Others     : 使能 LPTIM1 外设；
//               设置自动重装载值；
//               启动 One-Shot 单次计数模式；
//               ARR 匹配后产生中断请求，用于低功耗唤醒
*******************************************************************************/
void lptim_start(void);


/*******************************************************************************
//  Function   : lptim_stop
//  Description: 关闭 LPTIM1 并执行重新启动前的恢复延时
//  Param      : None
//  Return     : None
//  Others     : 关闭 LPTIM1 外设；
//               执行 LPTIM_RESTART_DELAY_NOP 次延时循环；
//               为下一次单次计数启动做准备
*******************************************************************************/
void lptim_stop(void);


#endif /* __BSP_LPTIM_H */
