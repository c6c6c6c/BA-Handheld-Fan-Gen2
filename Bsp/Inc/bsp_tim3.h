#ifndef _BSP_TIM3_H_
#define _BSP_TIM3_H_

#include "main.h"
#include "py32f032_ll_tim.h"

/* Macro -------------------------------------------------------------------------------------------------------------*/
/* 每个 TRGO 触发一次 ADC 规则组扫描；周期应大于完整扫描所需时间。 */
#define TIM3_ADC_SAMPLE_FREQUENCY_HZ     1000U

#if TIM3_ADC_SAMPLE_FREQUENCY_HZ == 0U
#error "TIM3_ADC_SAMPLE_FREQUENCY_HZ must be nonzero"
#endif

/* Function ----------------------------------------------------------------------------------------------------------*/
/*******************************************************************************
//  Function   : bsp_tim3_Init
//  Description: 初始化 TIM3 ADC 定周期触发
//  Param      : None
//  Return     : None
//  Others     : 根据实际定时器时钟计算 PSC/ARR，更新事件输出 TRGO；默认 1 kHz，
//               初始化后保持停止，不使用 GPIO、定时器中断或定时器 DMA 请求
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_tim3_Init(void);

/*******************************************************************************
//  Function   : bsp_tim3_Start
//  Description: 启动 TIM3 ADC 定周期触发
//  Param      : None
//  Return     : None
//  Others     : 初始化 TIM3 并启动 ADC/DMA 后调用；从完整周期开始触发，
//               已启动时重复调用不重置周期
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_tim3_Start(void);

/*******************************************************************************
//  Function   : bsp_tim3_Stop
//  Description: 停止 TIM3 ADC 定周期触发
//  Param      : None
//  Return     : None
//  Others     : 停止后不产生新触发，不取消 ADC 已经开始的转换
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_tim3_Stop(void);

/*******************************************************************************
//  Function   : bsp_tim3_Deinit
//  Description: 反初始化 TIM3
//  Param      : None
//  Return     : None
//  Others     : 停止触发、复位定时器并关闭 TIM3 外设时钟；停止 ADC 前应先停止 TIM3
//  Author     : Chen Liang 2026-10-12
*******************************************************************************/
void bsp_tim3_Deinit(void);

#endif /* _BSP_TIM3_H_ */
