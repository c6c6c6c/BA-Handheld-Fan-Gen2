#ifndef _APP_SAMPLING_H_
#define _APP_SAMPLING_H_

#include <stdint.h>


/* Typedef -----------------------------------------------------------------------------------------------------------*/

/**
 * @brief ADC 采样滤波通道类型
 */
typedef enum
{
    FILTER_LIST_NTC = 0,         /**< NTC 温度采样通道 */
    FILTER_LIST_MOTOR,           /**< 电机电流采样通道 */
    FILTER_LIST_MIST,            /**< 雾化片采样通道 */
    FILTER_LIST_SW,              /**< ADC 按键采样通道 */
    FILTER_LIST_NUM              /**< 滤波通道总数 */
} filter_list_t;


/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : app_sampling_Init
//  Description: 初始化应用层 ADC 采样滤波模块
//  Param      : None
//  Return     : None
//  Others     : 初始化 NTC、雾化片、电机及 ADC 按键对应的平均滤波器
//  Author     : Su Jiawei 2025-09-03
*******************************************************************************/
void app_sampling_Init(void);


/*******************************************************************************
//  Function   : app_sampling_task
//  Description: 执行应用层 ADC 平均滤波及 NTC 温度更新
//  Param      : None
//  Return     : None
//  Others     : 处理各通道采样数据；NTC 产生新滤波结果时更新系统温度及故障状态
//  Author     : Su Jiawei 2025-09-03
*******************************************************************************/
void app_sampling_task(void);


/*******************************************************************************
//  Function   : get_mist_val
//  Description: 获取雾化片 ADC 滤波结果
//  Param      : None
//  Return     : 雾化片 ADC 滤波值
//  Others     : 返回最近一次完成平均滤波的采样结果
//  Author     : Chen Liang 2026-10-18
*******************************************************************************/
uint16_t get_mist_val(void);


/*******************************************************************************
//  Function   : get_mist_seq
//  Description: 获取雾化片 ADC 滤波结果更新序号
//  Param      : None
//  Return     : 雾化片滤波结果更新序号
//  Others     : 序号变化表示有新的滤波结果，可用于追频算法判断采样是否更新
//  Author     : Chen Liang 2026-10-18
*******************************************************************************/
uint32_t get_mist_seq(void);


/*******************************************************************************
//  Function   : get_sw_val
//  Description: 获取 ADC 按键滤波结果
//  Param      : None
//  Return     : ADC 按键滤波值
//  Others     : 返回最近一次完成平均滤波的采样结果
//  Author     : Chen Liang 2026-10-18
*******************************************************************************/
uint16_t get_sw_val(void);


/*******************************************************************************
//  Function   : get_sw_seq
//  Description: 获取 ADC 按键滤波结果更新序号
//  Param      : None
//  Return     : ADC 按键滤波结果更新序号
//  Others     : 序号变化表示有新的按键 ADC 滤波数据
//  Author     : Chen Liang 2026-10-18
*******************************************************************************/
uint32_t get_sw_seq(void);


/*******************************************************************************
//  Function   : get_motor_val
//  Description: 获取电机电流 ADC 滤波结果
//  Param      : None
//  Return     : 电机电流 ADC 滤波值
//  Others     : 返回 ADC 原始量纲的滤波结果，尚未换算为实际电流
//  Author     : Chen Liang 2026-10-18
*******************************************************************************/
uint16_t get_motor_val(void);


/*******************************************************************************
//  Function   : get_motor_seq
//  Description: 获取电机电流 ADC 滤波结果更新序号
//  Param      : None
//  Return     : 电机电流滤波结果更新序号
//  Others     : 序号变化表示有新的电机电流滤波结果
//  Author     : Chen Liang 2026-10-18
*******************************************************************************/
uint32_t get_motor_seq(void);


#endif /* _APP_SAMPLING_H_ */
