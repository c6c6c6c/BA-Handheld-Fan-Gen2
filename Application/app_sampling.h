#ifndef _APP_SAMPLING_H_
#define _APP_SAMPLING_H_


/* Typedef -----------------------------------------------------------------------------------------------------------*/

/**
 * @brief 采样滤波通道类型
 */
typedef enum
{
    FILTER_LIST_NTC = 0,         /**< NTC 温度采样滤波 */
    FILTER_LIST_MOTOR,           /**< 电机电流采样滤波 */
    FILTER_LIST_SW,              /**< SW 信号采样滤波 */
    FILTER_LIST_NUM              /**< 滤波通道总数 */
} filter_list_t;


/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : app_sampling_Init
//  Description: 初始化应用层采样滤波模块
//  Param      : None
//  Return     : None
//  Others     : 初始化各采样通道的滤波状态及相关参数
//  Author     : Su Jiawei 2025-09-03
*******************************************************************************/
void app_sampling_Init(void);


/*******************************************************************************
//  Function   : app_sampling_task
//  Description: 应用层 ADC 采样滤波周期任务
//  Param      : None
//  Return     : None
//  Others     : 负责各采样通道的数据更新及滤波处理，调用周期由上层调度
//  Author     : Su Jiawei 2025-09-03
*******************************************************************************/
void app_sampling_task(void);


#endif /* _APP_SAMPLING_H_ */
