#ifndef _APP_BMS_H_
#define _APP_BMS_H_

#include "bms_config.h"


/* Variables ---------------------------------------------------------------------------------------------------------*/

/** BMS 全局电池运行数据，包含电压、电流、SOC、SOH、工作状态及保护故障 */
extern bms_battery_t bms_battery;


/* Function declarations ---------------------------------------------------------------------------------------------*/


/*******************************************************************************
//  Function   : app_bms_Restore
//  Description: 恢复掉电保存的电池 SOC、SOH 及累计电量数据
//  Param      : saved - 从非易失性存储器读取的电池历史数据
//  Return     : true：数据校验及恢复成功；false：数据无效或恢复失败
//  Others     : 应在 app_bms_ConfigureBattery() 成功后、周期任务启动前调用；
//               Flash 数据读取由上层实现，恢复失败时保留原运行数据
//  Author     : Chen Liang 2026-10-16
*******************************************************************************/
void app_bms_Restore(void);


/*******************************************************************************
//  Function   : app_bms_Save
//  Description: 生成当前电池 SOC、SOH 及累计电量的掉电保存数据
//  Param      : output - 电池数据快照输出缓冲区，不可为 NULL
//  Return     : true：数据生成成功；false：模块未初始化或运行数据无效
//  Others     : 仅生成数据快照，不执行 Flash 写入；应与 BMS 周期任务串行调用
//  Author     : Chen Liang 2026-10-16
*******************************************************************************/
void app_bms_Save(void);


/*******************************************************************************
//  Function   : app_bms_Init
//  Description: 初始化 BMS 应用层及相关功能模块
//  Param      : None
//  Return     : None
//  Others     : 初始化电池 ADC 换算模块及 IP5326 KEY 控制模块
//  Author     : Chen Liang 2026-10-16
*******************************************************************************/
void app_bms_Init(void);


/*******************************************************************************
//  Function   : app_bms_1ms_task
//  Description: BMS 应用层 1ms 周期任务
//  Param      : None
//  Return     : None
//  Others     : 周期推进 BMS 相关状态；ADC 累计采样完成后更新电池电压、
//               电流、充放电状态、软件保护及 SOC、SOH 运行数据
//  Author     : Chen Liang 2026-10-16
*******************************************************************************/
void app_bms_1ms_task(void);


#endif /* _APP_BMS_H_ */
