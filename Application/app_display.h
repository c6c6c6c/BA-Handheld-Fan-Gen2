#ifndef _APP_DISPLAY_H_
#define _APP_DISPLAY_H_

#include <stdbool.h>
#include <stdint.h>

#include "aip650e.h"


/* Typedef -----------------------------------------------------------------------------------------------------------*/

/**
 * @brief 应用层显示状态
 * @note  使用联合体保存数字、功能图标及原始显示状态数据。
 *        showNum[0] 用于 COM4 显示控制；
 *        showNum[1]、showNum[2] 分别用于 DIG1、DIG2 数字显示。
 */
typedef union
{
    uint8_t data[AIP650E_COM_COUNT];   /**< 显示状态原始数据数组 */

    struct
    {
        uint8_t showNum[3];            /**< 数字显示数据，取值由应用层定义 */
        uint8_t mist           : 1;    /**< 雾化功能图标状态 */
        uint8_t cooling        : 3;    /**< 制冷功能图标状态 */
        uint8_t percentageIcon : 1;    /**< 百分比图标状态 */
        uint8_t fanIcon        : 1;    /**< 风扇图标状态 */
        uint8_t reserved       : 2;    /**< 保留位 */
    } bit;

} app_display_t;


/* External variables ------------------------------------------------------------------------------------------------*/

/** 应用层显示状态，供其他业务模块更新显示内容 */
extern app_display_t display;

/** AiP650E 显示驱动实例，保存目标控制参数及 COM1~COM4 显示数据 */
extern aip650e_t aip650e;


/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : app_display_Init
//  Description: 初始化 AiP650E 显示应用模块
//  Param      : None
//  Return     : None
//  Others     : 初始化底层两线通信及显示芯片，并写入默认显示控制参数
//  Author     : Chen Liang 2026-10-21
*******************************************************************************/
void app_display_Init(void);


/*******************************************************************************
//  Function   : app_display_convert
//  Description: 将应用层显示状态转换为 AiP650E 显示寄存器数据
//  Param      : None
//  Return     : None
//  Others     : 根据数字及功能图标状态生成 COM1~COM4 显示数据，
//               数字超过 0~9 时熄灭对应数码管
//  Author     : Chen Liang 2026-10-21
*******************************************************************************/
void app_display_convert(void);


/*******************************************************************************
//  Function   : app_display_task
//  Description: 执行 AiP650E 显示刷新及控制状态同步
//  Param      : None
//  Return     : None
//  Others     : 正常情况下仅更新变化的显示数据及控制参数；
//               每隔约 1000ms 强制重新写入控制寄存器及全部 COM 数据
//  Author     : Chen Liang 2026-10-22
*******************************************************************************/
void app_display_task(void);


#endif /* _APP_DISPLAY_H_ */
