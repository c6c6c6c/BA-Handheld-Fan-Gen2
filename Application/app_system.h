#ifndef _APP_SYSTEM_H_
#define _APP_SYSTEM_H_

#include "main.h"
#include "app_logic.h"


/* Macro -------------------------------------------------------------------------------------------------------------*/

/** 系统看门狗使能配置，0=关闭，1=开启 */
#define SYSTEM_WDG_EN         0


/* Typedef -----------------------------------------------------------------------------------------------------------*/

/**
 * @brief 系统故障状态
 * @note  每个故障标志占用 1 位：
 *        0 表示正常，1 表示异常。
 */
typedef struct
{
    uint8_t bms_err  : 1;           /**< BMS 电池管理故障标志 */
    uint8_t comm_err : 1;           /**< 通信故障标志 */
    uint8_t ntc_err  : 1;           /**< NTC 温度检测故障标志 */
    uint8_t res      : 5;           /**< 保留位 */
} error_t;


/**
 * @brief 系统运行状态
 * @note  保存系统故障、开关机计时、主循环运行间隔、
 *        NTC 温度、休眠标志及应用层设备控制状态。
 */
typedef struct
{
    error_t     err;                /**< 系统故障状态 */

    uint32_t    systemLoopDelay;    /**< 相邻两次系统主循环的时间间隔，单位 ms */

    float       ntc_temp;           /**< 当前 NTC 检测温度，单位 ℃ */
    bool        sleep_flg;          /**< 系统休眠标志，true=休眠，false=正常运行 */

    app_logic_t logic;              /**< 应用层设备运行及控制逻辑状态 */
} system_t;


/* External variables ------------------------------------------------------------------------------------------------*/

/** 系统全局运行状态实例 */
extern system_t System;


/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : system_init
//  Description: 初始化系统底层驱动及应用功能模块
//  Param      : None
//  Return     : None
//  Others     : 系统启动时调用一次，依次完成底层硬件和应用模块初始化
//  Author     : 陈亮 2026-06-06
*******************************************************************************/
void system_init(void);


/*******************************************************************************
//  Function   : system_run
//  Description: 执行系统主循环及周期任务调度
//  Param      : None
//  Return     : None
//  Others     : 需要在主循环中持续调用，负责 ADC 采样处理、
//               风扇、按键、BMS、显示、通信及应用逻辑任务调度
//  Author     : 陈亮 2026-06-06
*******************************************************************************/
void system_run(void);


#endif /* _APP_SYSTEM_H_ */
