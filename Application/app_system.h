#ifndef _APP_SYSTEM_H_
#define _APP_SYSTEM_H_

#include "main.h"

/* Typedef -----------------------------------------------------------------------------------------------------------*/

#define SYSTEM_WDG_EN         0

/**
 * @brief 系统通信错误状态
 *
 * 每个错误状态使用一个位保存：
 * - 0：通信正常
 * - 1：通信异常
 */
typedef struct
{
    uint8_t bms_err    : 1;    /* BMS错误标志 */
    uint8_t comm_err   : 1;    /* 通信错误标志 */
    uint8_t res        : 6;    /* 保留位 */
} error_t;

/**
 * @brief 系统运行状态
 *
 * 保存系统开关机状态、风机档位、通信错误、
 * LED动画状态以及开关机和连续工作计时。
 */
typedef struct
{
    uint8_t         power;               /* 系统电源状态：0-关机，1-开机 */
    error_t         err;                 /* 系统通信错误状态 */

    uint8_t         forceFlg;            /* 强制控制标志 */

    uint32_t        onTimes;             /* 连续开机时间，单位：ms */
    uint32_t        offTimes;            /* 连续关机时间，单位：ms */
} system_t;

extern system_t System;
/* Function declarations ---------------------------------------------------------------------------------------------*/

/*******************************************************************************
//  Function   : system_init
//  Description: 初始化系统底层驱动、功能模块及通信模块
//  Param      : None
//  Return     : None
//  Others     : 系统启动时调用一次
//  Author     : 陈亮 2026-06-06
*******************************************************************************/
void system_init(void);

/*******************************************************************************
//  Function   : system_run
//  Description: 执行系统主循环任务
//  Param      : None
//  Return     : None
//  Others     : 需要在主循环中持续调用
//  Author     : 陈亮 2026-06-06
*******************************************************************************/
void system_run(void);

#endif

