#ifndef BMS_SOH_H
#define BMS_SOH_H

#include <stdbool.h>
#include <stdint.h>

#include "bms_config.h"

/***********************************************************************************************************************
//  Function   : bms_soh_init
//  Description: 绑定电池对象并根据累计放电量初始化 SOH
//  Param      : battery - 已设置 configInfo 的电池运行数据
//  Return     : true：初始化成功；false：对象或设计容量无效
//  Others     : 调用前应从有效的掉电数据恢复 discharge_mah_total；否则从零循环开始
//  Author     : Chen Liang 2026-10-16
***********************************************************************************************************************/
bool bms_soh_init(bms_battery_t *battery);

/***********************************************************************************************************************
//  Function   : bms_soh_update
//  Description: 将累计放电量折算为等效完整循环数并更新 SOH
//  Param      : battery - SOC 模块已更新累计放电量的电池运行数据
//  Return     : true：更新成功；false：对象或配置无效
//  Others     : 每放出一次设计容量视为一个等效完整循环；不依赖 BAT_STATE_FULL，
//               只更新运行数据，persist 由上层在保存时同步并计算校验值；
//               本模型是经验显示值，不能用作安全保护阈值
//  Author     : Chen Liang 2026-10-16
***********************************************************************************************************************/
bool bms_soh_update(bms_battery_t *battery);

#endif /* BMS_SOH_H */
